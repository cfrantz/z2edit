#!/usr/bin/env python3
"""Cross-reference z2edit's config/vanilla with the disassembly.

    config_xref.py [--symbols build/zelda2.sym.json] [--out FILE]

Lists every ROM address in config/vanilla/*.json5 (`{Prg: [bank, addr]}`)
with its key path, its name in the config, and the disassembly symbol at
that address (or `symbol+offset` for an address inside a table or an
instruction).  Writes a Markdown table (default:
docs/data-formats/config-xref.md).
"""
import argparse
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")


def load_labels(path):
    labels = {}
    for lab in json.load(open(path))["labels"]:
        labels.setdefault(lab["bank"], []).append((lab["addr"], lab["name"]))
    for v in labels.values():
        v.sort()
    return labels


def symbol_at(labels, bank, addr):
    best = None
    for a, name in labels.get(bank, []):
        if a > addr:
            break
        best = (a, name)
    if best is None:
        return "-"
    return best[1] if best[0] == addr else f"{best[1]}+{addr - best[0]}"


def entries(path):
    stack = []
    for line in open(path):
        indent = len(line) - len(line.lstrip())
        m = re.match(r'\s*"?([A-Za-z_0-9]+)"?\s*:', line)
        if m:
            while stack and stack[-1][0] >= indent:
                stack.pop()
            stack.append((indent, m.group(1)))
        name = re.search(r'name:\s*"([^"]*)"', line)
        for mm in re.finditer(r"([a-z_]+):\s*\{Prg:\s*\[(-?\d+),\s*0x([0-9a-fA-F]+)\]\}", line):
            bank = int(mm.group(2))
            yield ("/".join(k for _, k in stack[-4:]), name.group(1) if name else "",
                   7 if bank == -1 else bank, int(mm.group(3), 16))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--symbols", default=os.path.join(ROOT, "build/zelda2.sym.json"))
    p.add_argument("--out", default=os.path.join(ROOT, "docs/data-formats/config-xref.md"))
    args = p.parse_args()
    labels = load_labels(args.symbols)
    out = ["# z2edit Config Cross-Reference", "",
           "Generated by `tools/config_xref.py`: every ROM address in",
           "`config/vanilla/*.json5` and the disassembly symbol there.  An offset",
           "(`Name+k`) means the address is inside a table, or inside an",
           "instruction (a patch point, e.g. an immediate operand).", ""]
    for path in sorted(glob.glob(os.path.join(ROOT, "../config/vanilla/*.json5"))):
        rows = list(entries(path))
        if not rows:
            continue
        out += [f"## {os.path.basename(path)}", "",
                "| Key | Name | Bank | Address | Symbol |",
                "|-----|------|-----:|---------|--------|"]
        for key, name, bank, addr in rows:
            sym = symbol_at(labels, bank, addr)
            out.append(f"| {key} | {name} | {bank} | ${addr:04X} | {sym} |")
        out.append("")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
